  const STRINGS = { en, tr, de, es };

  /** Picks the best supported language for a BCP-47 tag like "tr-TR" */
  function resolve(tag) {
    const base = String(tag || '').toLowerCase().split(/[-_]/)[0];
    return STRINGS[base] ? base : 'en';
  }

  /** Translates a key. vars fill {placeholders}; function values receive vars. */
  function translate(lang, key, vars = {}) {
    const v = (STRINGS[lang] && STRINGS[lang][key]) ?? en[key];
    if (v == null) return key;
    if (typeof v === 'function') return v(vars);
    return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  }

  /** For values that may be plain text or an object of translations ({ en: '…', tr: '…' }) */
  function pick(lang, value) {
    if (value == null || typeof value !== 'object') return value ?? '';
    return value[lang] ?? value.en ?? Object.values(value)[0] ?? '';
  }

  const I18N = { LANGUAGES, STRINGS, resolve, translate, pick };
